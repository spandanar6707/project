    let studentId = students[0]?.student_id;
    if (!studentId) {
      const [res] = await connection.query(
        `INSERT INTO students (usn, full_name, email, department, semester, password_hash) 
         VALUES ('1MS23CS001', 'Load Test Student', 'teststudent@college.edu', 'Computer Science', 5, '$2b$12$e/samplehashedpasswordplaceholder');`
      );
      studentId = res.insertId;
    }

    // 2. Ensure test document type exists
    const [docTypes] = await connection.query('SELECT document_type_id FROM document_types WHERE is_active = 1 LIMIT 1;');
    let docTypeId = docTypes[0]?.document_type_id;
